import { render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { vi } from 'vitest'
import ReviewForm from './ReviewForm'
it('[TC-FE-REVIEW-01] allows local drafting but disables publishing without a real integration', async () => {
  const save = vi.fn()
  render(<ReviewForm onSubmit={save} />)
  await userEvent.click(screen.getByRole('button', { name: 'Rate 4 stars' }))
  expect(screen.getByRole('button', { name: 'Rate 4 stars' })).toHaveAttribute('aria-pressed', 'true')
  await userEvent.type(screen.getByRole('textbox'), 'Draft')
  expect(screen.getByRole('button', { name: 'Submit review' })).toBeDisabled()
  expect(screen.getByRole('status')).toHaveTextContent('Drafts are not saved')
  expect(save).not.toHaveBeenCalled()
})
it('[TC-FE-REVIEW-02] validates a rating and keeps a failed draft for retry', async () => {
  const save = vi.fn().mockRejectedValue(new Error('Service unavailable'))
  render(<ReviewForm available onSubmit={save} />)
  await userEvent.click(screen.getByRole('button', { name: 'Submit review' }))
  expect(screen.getByRole('alert')).toHaveTextContent('Choose a rating')
  expect(save).not.toHaveBeenCalled()
  await userEvent.click(screen.getByRole('button', { name: 'Rate 5 stars' }))
  await userEvent.type(screen.getByRole('textbox'), '  Loved it  ')
  await userEvent.click(screen.getByRole('button', { name: 'Submit review' }))
  expect(save).toHaveBeenCalledWith({ rating: 5, text: 'Loved it' })
  expect(screen.getByRole('alert')).toHaveTextContent('Service unavailable')
  expect(screen.getByRole('textbox')).toHaveValue('  Loved it  ')
  expect(screen.queryByText('Review saved.')).not.toBeInTheDocument()
})
it('[TC-RATE-01] shows confirmation only after persistence resolves', async () => {
  let resolve
  const save = vi.fn().mockReturnValue(new Promise(done => { resolve = done }))
  render(<ReviewForm available onSubmit={save} />)
  await userEvent.click(screen.getByRole('button', { name: 'Rate 3 stars' }))
  await userEvent.click(screen.getByRole('button', { name: 'Submit review' }))
  expect(screen.getByRole('button', { name: 'Saving…' })).toBeDisabled()
  expect(screen.queryByText('Review saved.')).not.toBeInTheDocument()
  resolve()
  expect(await screen.findByText('Review saved.')).toBeInTheDocument()
})
it('[TC-FE-RATE-03] allows rating-only submission with optional text', async () => {
  const save = vi.fn().mockResolvedValue(undefined)
  render(<ReviewForm available onSubmit={save} />)
  await userEvent.click(screen.getByRole('button', { name: 'Rate 1 stars' }))
  await userEvent.click(screen.getByRole('button', { name: 'Submit review' }))
  expect(save).toHaveBeenCalledWith({ rating: 1, text: '' })
  expect(await screen.findByText('Review saved.')).toBeInTheDocument()
})
it('[TC-FE-RATE-04] never enables publishing from an availability flag without a persistence callback', () => {
  render(<ReviewForm available />)
  expect(screen.getByRole('button', { name: 'Submit review' })).toBeDisabled()
  expect(screen.getByRole('status')).toHaveTextContent('unavailable')
})
it('[TC-FE-RATE-05] retains the character limit and counter at the 2000-character boundary', async () => {
  const save = vi.fn().mockResolvedValue(undefined)
  render(<ReviewForm available onSubmit={save} />)
  const text = screen.getByRole('textbox', { name: /your review/i })
  expect(text).toHaveAttribute('maxlength', '2000')
  await userEvent.click(text)
  await userEvent.paste('x'.repeat(2000))
  expect(screen.getByText('2000/2000 characters')).toBeInTheDocument()
  await userEvent.type(text, 'z')
  expect(text).toHaveValue('x'.repeat(2000))
  await userEvent.click(screen.getByRole('button', { name: 'Rate 2 stars' }))
  await userEvent.click(screen.getByRole('button', { name: 'Submit review' }))
  expect(save).toHaveBeenCalledWith({ rating: 2, text: 'x'.repeat(2000) })
})
it('[TC-FE-RATE-06] does not discard a new draft while an earlier submission is pending', async () => {
  let resolve
  const save = vi.fn().mockReturnValue(new Promise(done => { resolve = done }))
  render(<ReviewForm available onSubmit={save} />)
  await userEvent.click(screen.getByRole('button', { name: 'Rate 4 stars' }))
  await userEvent.type(screen.getByRole('textbox'), 'Pending draft')
  await userEvent.click(screen.getByRole('button', { name: 'Submit review' }))
  expect(screen.getByRole('textbox')).toBeDisabled()
  expect(screen.getByRole('button', { name: 'Rate 1 stars' })).toBeDisabled()
  await userEvent.click(screen.getByRole('button', { name: 'Saving…' }))
  expect(save).toHaveBeenCalledTimes(1)
  resolve()
  expect(await screen.findByText('Review saved.')).toBeInTheDocument()
  expect(screen.getByRole('textbox')).toHaveValue('')
  expect(screen.getByRole('button', { name: 'Rate 4 stars' })).toHaveAttribute('aria-pressed', 'false')
})
it('[TC-FE-RATE-07] removes stale success feedback when a new draft begins', async () => {
  render(<ReviewForm available onSubmit={vi.fn().mockResolvedValue(undefined)} />)
  await userEvent.click(screen.getByRole('button', { name: 'Rate 5 stars' }))
  await userEvent.click(screen.getByRole('button', { name: 'Submit review' }))
  await screen.findByText('Review saved.')
  await userEvent.type(screen.getByRole('textbox'), 'New draft')
  expect(screen.queryByText('Review saved.')).not.toBeInTheDocument()
})
it('[TC-FE-RATE-08] uses an accessible fallback error and supports retry without losing text', async () => {
  const save = vi.fn().mockRejectedValueOnce({}).mockResolvedValueOnce(undefined)
  render(<ReviewForm available onSubmit={save} />)
  await userEvent.click(screen.getByRole('button', { name: 'Rate 3 stars' }))
  await userEvent.type(screen.getByRole('textbox'), 'Retry draft')
  await userEvent.click(screen.getByRole('button', { name: 'Submit review' }))
  expect(await screen.findByRole('alert')).toHaveTextContent('could not be saved')
  expect(screen.getByRole('textbox')).toHaveValue('Retry draft')
  await userEvent.click(screen.getByRole('button', { name: 'Submit review' }))
  expect(await screen.findByText('Review saved.')).toBeInTheDocument()
  expect(screen.queryByRole('alert')).not.toBeInTheDocument()
  expect(save).toHaveBeenCalledTimes(2)
})
