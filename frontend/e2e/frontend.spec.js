import { test, expect } from '@playwright/test'

async function signedOut(page) {
  await page.route('**/api/auth/me', route => route.fulfill({ status: 401, contentType: 'application/json', body: JSON.stringify({ error: { message: 'Please sign in.' } }) }))
}
async function fitsViewport(page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
}
test('[TC-FE-BROWSER-01] homepage navigation fits the viewport and links reach auth pages', async ({ page }) => {
  await signedOut(page)
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /rate, review, and track/i })).toBeVisible()
  await fitsViewport(page)
  await expect(page.getByRole('link', { name: 'Join now', exact: true })).toHaveCount(1)
  await page.getByRole('link', { name: 'Join now', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Welcome to SideQuest' })).toBeVisible()
  await page.getByRole('link', { name: 'Log in here' }).click()
  await expect(page.getByRole('heading', { name: 'Sign in to continue' })).toBeVisible()
  expect(errors).toEqual([])
})
test('[TC-FE-BROWSER-02] keyboard skip navigation becomes visible and targets main content', async ({ page }) => {
  await signedOut(page)
  await page.goto('/')
  await page.keyboard.press('Tab')
  const skip = page.getByRole('link', { name: 'Skip to content' })
  await expect(skip).toBeFocused()
  await expect(skip).toBeInViewport()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/#main-content$/)
})
test('[TC-FE-BROWSER-03] discovery controls reset without horizontal overflow', async ({ page }) => {
  await signedOut(page)
  await page.goto('/games')
  await page.getByRole('searchbox').fill('Synthetic search')
  await page.getByRole('combobox', { name: 'Sort games' }).selectOption('reviews')
  await page.getByRole('button', { name: 'Reset filters' }).click()
  await expect(page.getByRole('searchbox')).toHaveValue('')
  await expect(page.getByRole('combobox', { name: 'Sort games' })).toHaveValue('title')
  await expect(page.getByRole('heading', { name: 'Catalog unavailable' })).toBeVisible()
  await fitsViewport(page)
})
test('[TC-FE-BROWSER-04] long card titles stay inside cards and above metadata', async ({ page }) => {
  await page.route('**/intentionally-missing-synthetic-artwork.svg', route => route.fulfill({ status: 404, body: '' }))
  await page.goto('/e2e/fixtures/cards.html')
  const card = page.getByRole('article').first()
  const title = await card.getByRole('heading').boundingBox()
  const metadata = await card.locator('.star-row').boundingBox()
  const bounds = await card.boundingBox()
  expect(title.y + title.height).toBeLessThanOrEqual(metadata.y)
  expect(title.x + title.width).toBeLessThanOrEqual(bounds.x + bounds.width)
  await expect(card.getByRole('img', { name: /artwork unavailable/i })).toBeVisible()
  await expect(page.getByText(/not rated/i)).toBeVisible()
  await fitsViewport(page)
})
test('[TC-FE-BROWSER-05] signed-in library navigation remains usable and distinguishes unavailable lists', async ({ page }) => {
  await page.route('**/api/auth/me', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ user: { id: 'synthetic-browser-user', displayName: 'Synthetic Browser Player', email: 'browser@example.test', avatarUrl: '' } }) }))
  await page.goto('/profile')
  await expect(page.getByRole('heading', { name: 'Synthetic Browser Player' })).toBeVisible()
  const navigation = page.getByRole('navigation', { name: 'Main navigation' })
  await navigation.getByRole('link', { name: 'Wishlist' }).click()
  await expect(page.getByRole('heading', { name: 'Wishlist unavailable' })).toBeVisible()
  await navigation.getByRole('link', { name: 'Backlog' }).click()
  await expect(page.getByRole('heading', { name: 'Backlog unavailable' })).toBeVisible()
  await fitsViewport(page)
})
test('[TC-FE-BROWSER-06] private profile route reveals no list data or edit controls', async ({ page }) => {
  await signedOut(page)
  await page.goto('/users/synthetic-private-player')
  await expect(page.getByRole('heading', { name: 'Public profile unavailable' })).toBeVisible()
  await expect(page.getByRole('status')).toContainText('privacy enforcement')
  await expect(page.getByRole('article')).toHaveCount(0)
  await expect(page.getByRole('button', { name: /edit|delete/i })).toHaveCount(0)
})
test('[TC-FE-BROWSER-07] displays the local Google option without configuration banners', async ({ page }, testInfo) => {
  await signedOut(page)
  await page.goto('/login')
  const google = page.getByRole('button', { name: 'Continue with Google' })
  await expect(google).toBeVisible()
  await expect(google).toBeDisabled()
  const buttonBounds = await google.boundingBox()
  const dividerBounds = await page.locator('.auth-divider').boundingBox()
  expect(Math.abs(buttonBounds.x + buttonBounds.width / 2 - dividerBounds.x - dividerBounds.width / 2)).toBeLessThan(1)
  await page.screenshot({ path: testInfo.outputPath('google-signin.png'), fullPage: true })
  await expect(page.getByText(/not configured|until the application is configured/i)).toHaveCount(0)
  await fitsViewport(page)
})
